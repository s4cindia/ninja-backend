/**
 * Resolve a glyph name to a Unicode codepoint, or undefined if unknown/invalid.
 * Order: algorithmic uniXXXX / uXXXXXX → single-char ASCII name → AGL subset.
 */
export function glyphNameToUnicode(name: string): number | undefined {
  if (!name) return undefined;
  const base = name.split('.')[0]; // strip suffix like ".sc" / ".oldstyle"

  const uni = base.match(/^uni([0-9A-Fa-f]{4})$/);
  if (uni) { const cp = parseInt(uni[1], 16); return isValidScalar(cp) ? cp : undefined; }
  const u = base.match(/^u([0-9A-Fa-f]{4,6})$/);
  if (u) { const cp = parseInt(u[1], 16); return isValidScalar(cp) ? cp : undefined; }

  if (base.length === 1) {
    const cc = base.charCodeAt(0);
    if (cc >= 0x21 && cc <= 0x7e) return cc;
  }
  return AGL[base];
}
