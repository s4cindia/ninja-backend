export const WINANSI_CODE_TO_UNICODE: readonly number[] = winAnsi;

/**
 * Resolve a named base encoding to its code→Unicode table.
 * Returns undefined for unknown / symbolic encodings (→ caller uses PUA).
 */
export function baseEncodingTable(name: string | undefined): readonly number[] | undefined {
  switch (name) {
    case '/WinAnsiEncoding': return winAnsi;
    case '/StandardEncoding': return standard;
    case '/MacRomanEncoding': return macRoman;
    default: return undefined; // MacExpert / symbolic / unknown built-in
  }
}

/** A valid, mappable Unicode scalar (BMP or astral, excluding surrogates). */
export function isValidScalar(cp: number): boolean {
  return cp > 0 && cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff);
}

